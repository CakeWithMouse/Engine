#pragma once

#include "../../Core/HlslGraphCompiler.h"
#include "../../Core/MaterialGraphModel.h"

#include <cstdio>
#include <cstdlib>

namespace
{

void CheckMatGraph(bool cond, const char* msg)
{
    if (!cond)
    {
        std::fprintf(stderr, "FAIL (MaterialGraph): %s\n", msg);
        std::exit(1);
    }
}

inline void RunMaterialGraphTests()
{
    using namespace EditorCore;

    // 1. Default setup and HLSL compilation
    {
        MaterialGraphModel model;
        model.SetupDefaultMasterNode();
        CheckMatGraph(model.Nodes().size() == 3, "Default model has 3 nodes");
        CheckMatGraph(model.Connections().size() == 2, "Default model has 2 connections");
        CheckMatGraph(model.Nodes()[0].type == QStringLiteral("MaterialOutput"), "Default model starts with the material output");

        QString hlsl = HlslGraphCompiler::CompileGraphToHlsl(model);
        CheckMatGraph(!hlsl.isEmpty(), "Compiled HLSL is not empty");
        CheckMatGraph(hlsl.contains(QStringLiteral("// Generated by PainEngine Material Node Graph")), "HLSL header present");
        CheckMatGraph(hlsl.contains(QStringLiteral("cbuffer MaterialParams : register(b1)")), "MaterialParams cbuffer present");
        CheckMatGraph(hlsl.contains(QStringLiteral("float4 BaseColor = float4(0.8627f, 0.8627f, 0.8824f, 1.0000f);")), "BaseColor float4 formatted in C-locale");
        CheckMatGraph(hlsl.contains(QStringLiteral("float Specular = 0.5000f;")), "Specular float formatted in C-locale");
        CheckMatGraph(hlsl.contains(QStringLiteral("void Surface(MaterialInput i, inout MaterialOutput o)")), "Surface function present");
        CheckMatGraph(hlsl.contains(QStringLiteral("o.Albedo = saturate(BaseColor.rgb);")), "Albedo mapped to BaseColor.rgb");
        CheckMatGraph(hlsl.contains(QStringLiteral("o.SpecularWeight = saturate(Specular);")), "SpecularWeight mapped to Specular");
        // Unconnected inputs keep the template defaults (component colour and texture, flat or hemispherical ambient).
        CheckMatGraph(!hlsl.contains(QStringLiteral("o.Alpha")) && !hlsl.contains(QStringLiteral("o.AmbientModel")) &&
                      !hlsl.contains(QStringLiteral("o.Normal")), "Unconnected outputs are not written");
        CheckMatGraph(!hlsl.contains(QStringLiteral("#define MATERIAL_EMISSIVE 1")), "No emissive defined by default");

        MaterialGraphModel empty;
        empty.AddNode(QStringLiteral("MaterialOutput"), QStringLiteral("Out"), QPointF(), {});
        CheckMatGraph(HlslGraphCompiler::CompileGraphToHlsl(empty).contains(QStringLiteral("inout MaterialOutput o)\n{\n}\n")), "Empty graph keeps the whole default surface");
    }

    // 2. Texture, Emissive and complex nodes
    {
        MaterialGraphModel model;
        model.SetupDefaultMasterNode();

        // Add Texture2D for BaseMap
        QVariantMap texProps;
        texProps[QStringLiteral("textureName")] = QStringLiteral("AlbedoMap");
        texProps[QStringLiteral("slot")] = 6;
        int texNode = model.AddNode(QStringLiteral("Texture2D"), QStringLiteral("Albedo Map"), QPointF(100, 100), texProps);

        // Disconnect BaseColor from the output and connect Texture2D RGB -> output Albedo
        model.RemoveConnection(2, QStringLiteral("RGB"), 1, QStringLiteral("Albedo"));
        model.AddConnection(texNode, QStringLiteral("RGB"), 1, QStringLiteral("Albedo"));

        // Add ColorParam for Emissive
        QVariantMap emissiveProps;
        emissiveProps[QStringLiteral("name")] = QStringLiteral("GlowColor");
        emissiveProps[QStringLiteral("color")] = QColor(255, 128, 0);
        int emissiveNode = model.AddNode(QStringLiteral("ColorParam"), QStringLiteral("Glow"), QPointF(100, 450), emissiveProps);
        model.AddConnection(emissiveNode, QStringLiteral("RGB"), 1, QStringLiteral("Emissive"));

        QString hlsl = HlslGraphCompiler::CompileGraphToHlsl(model);
        CheckMatGraph(hlsl.contains(QStringLiteral("#define MATERIAL_EMISSIVE 1")), "Emissive macro present when connected");
        CheckMatGraph(hlsl.contains(QStringLiteral("Texture2D AlbedoMap : register(t6);")), "Texture declaration present");
        CheckMatGraph(hlsl.contains(QStringLiteral("AlbedoMap.Sample(MaterialSampler, i.UV).rgb")), "Texture sampling expression present");
        CheckMatGraph(hlsl.contains(QStringLiteral("o.Emissive = GlowColor.rgb;")), "Emissive assigned to output");
    }

    // 2b. Default graph links use real pins; Panner and NormalMap compile; texture names and registers stay unique
    {
        MaterialGraphModel model;
        model.SetupDefaultMasterNode();
        for (const auto& c : model.Connections())
            CheckMatGraph(c.fromPin != QStringLiteral("Param"), "Default graph links scalar pins by their real name");

        const int a = model.AddNode(QStringLiteral("Texture2D"), QStringLiteral("A"), QPointF(), {});
        const int b = model.AddNode(QStringLiteral("Texture2D"), QStringLiteral("B"), QPointF(), {{QStringLiteral("textureName"), QStringLiteral("Detail")}});
        const int same = model.AddNode(QStringLiteral("Texture2D"), QStringLiteral("A again"), QPointF(), {});
        QVariantMap pannerProps;
        pannerProps[QStringLiteral("speedX")] = 0.25;
        pannerProps[QStringLiteral("speedY")] = -1.0;
        const int panner = model.AddNode(QStringLiteral("Panner"), QStringLiteral("Panner"), QPointF(), pannerProps);
        const int normal = model.AddNode(QStringLiteral("NormalMap"), QStringLiteral("Normal"), QPointF(), {});
        const int mul = model.AddNode(QStringLiteral("Multiply"), QStringLiteral("Mul"), QPointF(), {});
        model.RemoveConnection(2, QStringLiteral("RGB"), 1, QStringLiteral("Albedo"));
        model.AddConnection(panner, QStringLiteral("UV_Out"), b, QStringLiteral("UV"));
        model.AddConnection(a, QStringLiteral("RGB"), mul, QStringLiteral("A"));
        model.AddConnection(b, QStringLiteral("RGB"), mul, QStringLiteral("B"));
        model.AddConnection(mul, QStringLiteral("Out"), 1, QStringLiteral("Albedo"));
        model.AddConnection(same, QStringLiteral("A"), 1, QStringLiteral("Alpha"));
        model.AddConnection(normal, QStringLiteral("Normal"), 1, QStringLiteral("Normal"));

        const QString hlsl = HlslGraphCompiler::CompileGraphToHlsl(model);
        CheckMatGraph(hlsl.count(QStringLiteral("Texture2D BaseMap :")) == 1, "Nodes sharing a texture name declare it once");
        CheckMatGraph(hlsl.contains(QStringLiteral("Texture2D BaseMap : register(t6);")) &&
                      hlsl.contains(QStringLiteral("Texture2D Detail : register(t7);")) &&
                      hlsl.contains(QStringLiteral("Texture2D NormalMap : register(t8);")), "Taken registers move to the next free one");
        CheckMatGraph(hlsl.contains(QStringLiteral("Detail.Sample(MaterialSampler, (i.UV + i.Time * float2(0.25f, -1.00f)))")), "Panner scrolls UV with time");
        CheckMatGraph(hlsl.contains(QStringLiteral("o.Normal = NormalFromMap(i, NormalMap.Sample(MaterialSampler, i.UV).xyz, 1.0f);")), "Normal map goes through the tangent frame helper");
    }

    // 3. Round-trip JSON test
    {
        MaterialGraphModel original;
        original.SetupDefaultMasterNode();

        // Add another node and connection
        QVariantMap multProps;
        int multNode = original.AddNode(QStringLiteral("Multiply"), QStringLiteral("Multiply"), QPointF(350, 200), multProps);
        original.AddConnection(multNode, QStringLiteral("Out"), 1, QStringLiteral("AmbientModel"));

        QString jsonStr = original.ExportToJson();
        CheckMatGraph(!jsonStr.isEmpty(), "JSON export not empty");

        MaterialGraphModel imported;
        bool ok = imported.ImportFromJson(jsonStr);
        CheckMatGraph(ok, "ImportFromJson succeeded");
        CheckMatGraph(imported.Nodes().size() == original.Nodes().size(), "Imported node count matches");
        CheckMatGraph(imported.Connections().size() == original.Connections().size(), "Imported connection count matches");

        for (int i = 0; i < original.Nodes().size(); ++i)
        {
            const auto& origN = original.Nodes()[i];
            const auto* impN = imported.FindNode(origN.id);
            CheckMatGraph(impN != nullptr, "Node found by id");
            CheckMatGraph(impN->type == origN.type, "Node type matches");
            CheckMatGraph(impN->title == origN.title, "Node title matches");
            CheckMatGraph(std::fabs(impN->pos.x() - origN.pos.x()) < 1e-4, "Node X matches");
            CheckMatGraph(std::fabs(impN->pos.y() - origN.pos.y()) < 1e-4, "Node Y matches");
        }

        // Re-export and verify exact identity
        QString reExport = imported.ExportToJson();
        CheckMatGraph(reExport == jsonStr, "Round-trip JSON is completely identical");

        // String properties stay strings: QString converts to QColor, so the type must be checked exactly.
        const auto* color = imported.FindNode(2);
        CheckMatGraph(color && color->properties.value(QStringLiteral("name")).toString() == QStringLiteral("BaseColor"), "Parameter name survives JSON");
        CheckMatGraph(color->properties.value(QStringLiteral("color")).value<QColor>() == QColor(220, 220, 225), "Color survives JSON");
        CheckMatGraph(!jsonStr.contains(QStringLiteral("\"name\": [")), "Names are not written as colors");
    }
}

} // namespace
