"""Regenerate embedded monochrome PNGs: python -m pip install resvg-py==0.5.0.

QtGui includes PNG support; these assets keep icons usable without optional QtSvg.
Run only when EditorIconData.h changes. Normal C++ builds need no Python/resvg.
"""
from pathlib import Path
import ast
import re
import resvg_py

root = Path(__file__).resolve().parent
source = (root / 'EditorIconData.h').read_text(encoding='utf-8-sig')
pattern = r'inline constexpr const char\* (\w+) = (R"SVG\((.*?)\)SVG"|"(?:\\.|[^"\\])*");'
entries = []
output = ['// Generated by generate-icon-fallbacks.py; do not edit.', '#pragma once',
          '#include "EditorIconData.h"', '#include <cstring>', 'namespace EditorIconFallbacks {']
for match in re.finditer(pattern, source, re.S):
    name, literal, raw = match.groups()
    svg = raw if raw is not None else ast.literal_eval(literal)
    svg = svg[svg.index('<svg'):].replace('currentColor', '#FFFFFF')
    png = resvg_py.svg_to_bytes(svg_string=svg, width=96, height=96)
    output.append(f'inline constexpr unsigned char {name}[] = {{')
    for i in range(0, len(png), 24):
        output.append('    ' + ','.join(str(b) for b in png[i:i+24]) + ',')
    output.append('};')
    entries.append(name)
assert len(entries) == source.count('inline constexpr const char*'), 'Unparsed SVG definition'
output += ['struct Asset { const unsigned char* data; int size; };',
           'inline Asset Find(const char* svg) {']
for name in entries:
    output.append(f'    if (std::strcmp(svg, EditorIcons::{name}) == 0) return {{{name}, sizeof({name})}};')
output += ['    return {nullptr, 0};', '}', '}']
(root / 'EditorIconFallbacks.h').write_text('\n'.join(output) + '\n', encoding='utf8')
print(f'Generated {len(entries)} embedded icons')
